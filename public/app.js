function filterTeachers(lang) {
  document.querySelectorAll('[data-language]').forEach(card => {
    const show = lang === 'all' || card.dataset.language === lang;
    card.classList.toggle('hidden', !show);
  });
  document.querySelectorAll('.sn-filter-btn').forEach(btn => {
    const isActive = btn.dataset.filter === lang;
    btn.classList.toggle('bg-white', isActive);
    btn.classList.toggle('shadow-sm', isActive);
    btn.classList.toggle('text-neutral-900', isActive);
    btn.classList.toggle('text-neutral-700', !isActive);
    btn.classList.toggle('hover:text-neutral-900', !isActive);
  });
}

