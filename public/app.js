function chooseTeacher(name, lang) {
  // contact-modal is `fixed inset-0` — opens as an overlay over the
  // current viewport. No scroll needed, no setTimeout — just show it.
  document.getElementById("contact-modal").classList.remove("hidden");
  document.getElementById("selected-teacher-field").classList.remove("hidden");
  // Translate teacher name and language based on current UI language
  const t = translations[currentLang] || translations['ru'];
  const nameKeyMap = {
    'Эрик': 'teacher_erik', 'Алехандро': 'teacher_alejandro',
    'Лара': 'teacher_lara', 'Лидия': 'teacher_lidia', 'Татьяна': 'teacher_tatyana'
  };
  const langKeyMap = {
    'Испанский язык': 'lang_spanish_full', 'Английский язык': 'lang_english_full',
    'Украинский язык': 'lang_ukrainian_full', 'Болгарский язык': 'lang_bulgarian_full'
  };
  const translatedName = t[nameKeyMap[name]] || name;
  const translatedLang = t[langKeyMap[lang]] || lang || '';
  document.getElementById("selectedTeacher").value = translatedName;
  document.getElementById("selectedTeacherLang").value = translatedLang;
  // hide the language dropdown since it's already known
  const langField = document.getElementById("form-lang-field");
  const langSelect = document.getElementById("form-lang-select");
  langField.classList.add("hidden");
  langSelect.removeAttribute("required");
  langSelect.value = "";
}

document.getElementById("contact-form").addEventListener("submit", async (e) => {
  e.preventDefault();
  const form = e.currentTarget;
  const btn = document.getElementById("contact-submit");
  const errEl = document.getElementById("contact-error");
  const t = translations[currentLang];
  btn.disabled = true;
  btn.textContent = t.form_sending;
  errEl.classList.add("hidden");
  try {
    const res = await fetch("https://formspree.io/f/xpqbaqyr", {
      method: "POST", body: new FormData(form), headers: { Accept: "application/json" },
    });
    if (!res.ok) throw new Error();
    form.classList.add("hidden");
    const s = document.getElementById("contact-success");
    s.textContent = t.modal_success;
    s.classList.remove("hidden");
    setTimeout(closeContactModal, 2000);
  } catch {
    errEl.textContent = t.form_error;
    errEl.classList.remove("hidden");
    btn.disabled = false;
    btn.textContent = t.form_submit;
  }
});

function toggleMobileMenu() {
  const menu = document.getElementById('mobile-menu');
  const btn = document.getElementById('burger-btn');
  const icon = document.getElementById('burger-icon');
  const isOpening = menu.classList.contains('hidden');
  menu.classList.toggle('hidden', !isOpening);
  btn.setAttribute('aria-expanded', isOpening ? 'true' : 'false');
  // swap icon: 3 lines ↔ ✕
  icon.innerHTML = isOpening
    ? '<path stroke-linecap="round" stroke-linejoin="round" d="M6 6L18 18M6 18L18 6"/>'
    : '<path stroke-linecap="round" stroke-linejoin="round" d="M4 6h16M4 12h16M4 18h16"/>';
}

function closeMobileMenu() {
  const menu = document.getElementById('mobile-menu');
  if (!menu.classList.contains('hidden')) toggleMobileMenu();
}

function toggleLangDropdown() {
  const menu = document.getElementById('lang-dropdown-menu');
  const arrow = document.getElementById('lang-dropdown-arrow');
  const isOpen = !menu.classList.contains('hidden');
  menu.classList.toggle('hidden', isOpen);
  arrow.style.transform = isOpen ? '' : 'rotate(180deg)';
}

function selectLang(lang, label) {
  document.getElementById('lang-dropdown-label').textContent = label;
  document.getElementById('lang-dropdown-menu').classList.add('hidden');
  document.getElementById('lang-dropdown-arrow').style.transform = '';
  // update checkmarks
  document.querySelectorAll('.sn-lang-option').forEach(btn => {
    const check = btn.querySelector('.sn-lang-check');
    if (btn.getAttribute('data-lang') === lang) {
      check.classList.remove('hidden');
      btn.classList.add('font-semibold');
    } else {
      check.classList.add('hidden');
      btn.classList.remove('font-semibold');
    }
  });
  setLang(lang);
}

// Close dropdown on outside click
document.addEventListener('click', function(e) {
  const wrap = document.getElementById('lang-dropdown-wrap');
  if (wrap && !wrap.contains(e.target)) {
    document.getElementById('lang-dropdown-menu').classList.add('hidden');
    document.getElementById('lang-dropdown-arrow').style.transform = '';
  }
});
