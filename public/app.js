let currentLang = 'ru';

function setLang(lang) {
  currentLang = lang;
  const t = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.placeholder = t[key];
  });

  // dropdown label already updated by selectLang

  document.documentElement.lang = lang;

  // re-trigger handwrite animation with new text
  const hwText = document.getElementById('handwrite-text');
  if (hwText) {
    const phrase = t.handwrite || '';
    // rebuild spans
    let html = '';
    for (let i = 0, idx = 0; i < phrase.length; i++) {
      if (phrase[i] === ' ') {
        html += '<span class="sn-hw-space">&nbsp;</span>';
      } else {
        html += `<span style="--i:${idx}">${phrase[i]}</span>`;
        idx++;
      }
    }
    hwText.innerHTML = html;
    hwText.setAttribute('aria-label', phrase);
  }
}

